from django.contrib import admin
from django.urls import path, include, re_path
from django.conf import settings
from django.conf.urls.static import static
from rest_framework import permissions
from drf_yasg.views import get_schema_view
from drf_yasg import openapi

schema_view = get_schema_view(
    openapi.Info(
        title="SASS Platform API",
        default_version='v1',
        description=(
            "Interactive Swagger UI for API testing and exploration.\n\n"
            "### How to Authenticate for Protected Endpoints:\n"
            "1. Obtain a token via `/core/api/token/`\n"
            "2. Click the **Authorize** button on the top right\n"
            "3. Enter `Bearer <your_access_token>`\n"
            "4. Test protected endpoints directly from Swagger UI!"
        ),
        terms_of_service="https://www.google.com/policies/terms/",
        contact=openapi.Contact(email="support@sass.local"),
        license=openapi.License(name="BSD License"),
    ),
    public=True,
    permission_classes=(permissions.AllowAny,),
    authentication_classes=(),
)

urlpatterns = [
    path('admin/', admin.site.urls),
    path('core/', include('core.urls')),
    path('group/', include('group.urls')),

    # Swagger UI & OpenAPI Specification Routes
    re_path(r'^swagger(?P<format>\.json|\.yaml)$', schema_view.without_ui(cache_timeout=0), name='schema-json'),
    path('swagger/', schema_view.with_ui('swagger', cache_timeout=0), name='schema-swagger-ui'),
    path('redoc/', schema_view.with_ui('redoc', cache_timeout=0), name='schema-redoc'),
    path('', schema_view.with_ui('swagger', cache_timeout=0), name='schema-root'),
]

if settings.DEBUG:
    urlpatterns += static(settings.STATIC_URL, document_root=settings.STATIC_ROOT)
    urlpatterns += static(settings.MEDIA_URL, document_root=settings.MEDIA_ROOT)

